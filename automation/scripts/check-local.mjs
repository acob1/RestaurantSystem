import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadPrivateEnv, ready, request } from './lib.mjs';
const supplied=process.argv.indexOf('--env-file');
const file=supplied>=0 ? resolve(process.argv[supplied+1]??'') : new URL('../.env.local',import.meta.url);
const env=loadPrivateEnv(file);
const port=env['AUTOMATION_PORT']??'5678';
if(!/^\d{1,5}$/.test(port)||Number(port)<1||Number(port)>65535) throw new Error('Invalid local automation port.');
if(!env['RESTAURANT_WEBHOOK_TOKEN']) throw new Error('Webhook token is missing from your private environment file.');
const base=`http://127.0.0.1:${port}`;
await ready(base);
const body=JSON.parse(readFileSync(new URL('../tests/fixtures/valid-message.json',import.meta.url)));
const timeoutFlag=process.argv.indexOf('--timeout-ms');
const timeoutMs=timeoutFlag>=0?Number(process.argv[timeoutFlag+1]):15000;
assert.ok(Number.isInteger(timeoutMs)&&timeoutMs>=1000&&timeoutMs<=120000,'Timeout must be 1000–120000 milliseconds.');
const result=await request(base,body,env['RESTAURANT_WEBHOOK_TOKEN'],'POST',timeoutMs);
assert.equal(result.status,200,'Create the Header Auth credential and publish the first workflow in the n8n editor.');
assert.equal(result.data.ok,true);assert.equal(result.data.mode,'development');
console.log('Local n8n readiness and authenticated development webhook passed.');
